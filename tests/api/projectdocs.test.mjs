// Model đọc được toàn bộ tệp dài của dự án: đọc tuần tự, tìm từ khóa không dấu. Tự chạy được, không cần dev:mock.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { loadTs } from "../lib/ts.mjs";
let pass = 0, fail = 0;
const ok = (c, n, x = "") => { c ? pass++ : fail++; console.log(c ? "  ✓" : "  ✗", n, c ? "" : String(typeof x === "string" ? x : JSON.stringify(x)).slice(0, 400)); };
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), "synchro-projdocs-"));
process.env.DATA_KEY = "k";
const { authstore: AS, chatstore: CS, projectdocs: P } = await loadTs(["authstore", "chatstore", "projectdocs"]);
const u = AS.createUser({ email: "a@p.test", name: "A", verified: true }), v = AS.createUser({ email: "b@p.test", name: "B", verified: true });
const long = "Điều khoản mở đầu. ".repeat(8000) + "Điều 41: mức bồi thường thiệt hại là 8% giá trị hợp đồng. " + "Phần kết. ".repeat(2000);
CS.pushItems(u.id, [{ kind: "project", id: "7", upd: Date.now(), data: JSON.stringify({ id: 7, name: "HĐ", ctx: [{ name: "hopdong.txt", text: long }, { name: "cu.txt", chunks: ["đoạn một", "đoạn hai"] }] }) }]);
ok(P.projectDocs(u.id, 7).length === 2 && P.projectDocs(u.id, 7)[1].text.includes("đoạn hai"), "đọc được cả tệp cũ chỉ có đoạn đã chia");
ok(P.projectDocsLong(u.id, 7), "tệp dài: có công cụ đọc");
ok(P.projectDocs(v.id, 7).length === 0, "người khác không đọc được dự án của mình");
ok(P.projectDocs(u.id, 999).length === 0 && !P.projectDocsLong(u.id, undefined), "dự án chưa đồng bộ: không có gì, không lỗi");
const r = P.readProjectFile(u.id, 7, { query: "boi thuong" });
ok(!r.is_error && r.content.includes("8% giá trị hợp đồng"), "tìm không dấu ra đúng điều khoản nằm rất xa phần đầu", r.content.slice(0, 200));
const at = Number(/\[vị trí (\d+)\]/.exec(r.content)?.[1]);
ok(long.normalize("NFC").slice(at, at + 700).includes("Điều 41"), "vị trí trả về dùng lại được", at);
const none = P.readProjectFile(u.id, 7, { query: "khongcotutrongtep" });
ok(!none.is_error && /thử cách gọi khác/.test(none.content), "không thấy: gợi ý đổi từ khóa");
const page = P.readProjectFile(u.id, 7, { offset: 0 });
ok(/Đọc tiếp bằng offset 30000/.test(page.content), "đọc tuần tự có chỉ dẫn đọc tiếp", page.content.slice(0, 120));
ok(/Đã hết tệp/.test(P.readProjectFile(u.id, 7, { file: "cu.txt" }).content), "tệp ngắn đọc hết");
ok(P.readProjectFile(u.id, 7, { file: "khong-co" }).is_error, "sai tên tệp: báo lỗi kèm danh sách");
console.log(`\n${pass} đạt, ${fail} lỗi`);
process.exit(fail ? 1 : 0);
